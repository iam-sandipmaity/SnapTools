const ASCIIArtGenerator = () => {
  const [inputText, setInputText] = useState("");
  const [fontStyle, setFontStyle] = useState<keyof typeof ASCII_FONTS>("block");
  const [asciiArt, setAsciiArt] = useState<string>("");

  const generateASCIIArt = (text: string, font: keyof typeof ASCII_FONTS) => {
    if (!text) {
      setAsciiArt("");
      return;
    }

    const upperText = text.toUpperCase();
    const fontData = ASCII_FONTS[font].chars;
    const lineCount = Object.values(fontData)[0].length;
    const lines: string[] = Array(lineCount).fill("");

    for (let i = 0; i < upperText.length; i++) {
      const char = upperText[i];
      const charData = fontData[char as keyof typeof fontData];

      if (charData) {
        for (let j = 0; j < lineCount; j++) {
          lines[j] += charData[j] + " ";
        }
      } else {
        // If character not supported, use space
        for (let j = 0; j < lineCount; j++) {
          lines[j] += fontData[" "][j] + " ";
        }
      }
    }

    setAsciiArt(lines.join("\n"));
  };

  const handleTextChange = (e: React.ChangeEvent<HTMLInputElement>) => {
    const text = e.target.value.slice(0, 20); // Limit to 20 characters
    setInputText(text);
    generateASCIIArt(text, fontStyle);
  };

  const handleFontChange = (value: string) => {
    const font = value as keyof typeof ASCII_FONTS;
    setFontStyle(font);
    if (inputText) {
      generateASCIIArt(inputText, font);
    }
  };

  const handleCopy = async () => {
    if (!asciiArt) {
      toast.error("Nothing to copy");
      return;
    }
    try {
      await navigator.clipboard.writeText(asciiArt);
      toast.success("ASCII art copied to clipboard!");
    } catch (error) {
      toast.error("Failed to copy to clipboard");
    }
  };

  const handleDownload = () => {
    if (!asciiArt) {
      toast.error("Nothing to download");
      return;
    }

    const blob = new Blob([asciiArt], { type: "text/plain" });
    const url = URL.createObjectURL(blob);
    const a = document.createElement("a");
    a.href = url;
    a.download = `ascii-art-${inputText || "output"}.txt`;
    a.click();
    URL.revokeObjectURL(url);
    toast.success("ASCII art downloaded!");
  };

  return (
    <AnimatedElement className="space-y-6">
      <div className="border rounded-lg p-6 bg-gradient-to-br from-muted/40 to-muted/20 space-y-6">
        <div className="text-sm text-muted-foreground">
          <p className="font-medium text-foreground mb-1 text-lg flex items-center gap-2">
            <Sparkles className="h-5 w-5 text-primary" />
            🎨 ASCII Art Generator
          </p>
          <p>Convert text into creative ASCII art designs</p>
        </div>

        {/* Input Section */}
        <div className="space-y-3">
          <Label htmlFor="text-input" className="text-base font-semibold">
            Enter Text
          </Label>
          <Input
            id="text-input"
            placeholder="Enter text to convert..."
            value={inputText}
            onChange={handleTextChange}
            maxLength={20}
            className="text-lg"
          />
          <p className="text-xs text-muted-foreground">
            {inputText.length}/20 characters
          </p>
        </div>

        {/* Font Style Selection */}
        <div className="space-y-3">
          <Label htmlFor="font-style" className="text-base font-semibold">
            Font Style
          </Label>
          <Select value={fontStyle} onValueChange={handleFontChange}>
            <SelectTrigger id="font-style">
              <SelectValue />
            </SelectTrigger>
            <SelectContent>
              {Object.entries(ASCII_FONTS).map(([key, value]) => (
                <SelectItem key={key} value={key}>
                  {value.name}
                </SelectItem>
              ))}
            </SelectContent>
          </Select>
        </div>

        {/* Output Section */}
        {asciiArt && (
          <div className="space-y-3">
            <div className="flex items-center justify-between">
              <Label className="text-base font-semibold">ASCII Art Output</Label>
              <div className="flex gap-2">
                <Button variant="outline" size="sm" onClick={handleCopy}>
                  <Copy className="h-4 w-4 mr-2" />
                  Copy
                </Button>
                <Button variant="outline" size="sm" onClick={handleDownload}>
                  <Download className="h-4 w-4 mr-2" />
                  Download
                </Button>
              </div>
            </div>
            <div className="relative">
              <pre className="p-6 bg-background border-2 rounded-lg font-mono text-xs sm:text-sm overflow-x-auto whitespace-pre leading-tight shadow-inner">
                {asciiArt}
              </pre>
            </div>
          </div>
        )}

        {/* Tips Section */}
        <div className="border rounded-lg p-4 bg-gradient-to-r from-blue-50 to-cyan-50 dark:from-blue-950/30 dark:to-cyan-950/30">
          <div className="flex items-start gap-3">
            <AlertCircle className="h-5 w-5 text-blue-600 dark:text-blue-400 mt-0.5 flex-shrink-0" />
            <div className="space-y-2 text-sm">
              <p className="font-semibold text-foreground">💡 Tips</p>
              <ul className="space-y-1 text-muted-foreground list-disc list-inside">
                <li>Keep text short for best results (max 20 characters)</li>
                <li>ASCII art looks best in monospace fonts</li>
                <li>Copy and paste into emails, comments, or social media</li>
                <li>Try different font styles for various effects</li>
              </ul>
            </div>
          </div>
        </div>
      </div>
    </AnimatedElement>
  );
};

export default ASCIIArtGenerator;
